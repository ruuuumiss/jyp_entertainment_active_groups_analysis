def get_stats(df, name):
  noms = df.groupby('Year').size()
  wins = df[df['Result'] == 'Won'].groupby('Year').size()

  temp_df = pd.DataFrame({'Nominations': noms, 'Wins': wins}).fillna(0)
  temp_df['Artist'] = name
  temp_df['Year'] = temp_df.index.astype(int)
  return temp_df

