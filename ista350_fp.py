user_agent = {'User-agent':'Mozilla/5.0'}
def url_to_df(url):
    res = requests.get(url, headers=user_agent)
    wiki_soup = BeautifulSoup(res.content, "html.parser")
    all_tables = wiki_soup.find_all("table")
    target_table = None
    for table in all_tables:
      header_txt = table.get_text().lower()
      if "award ceremony" in header_txt and "result" in header_txt:
        target_table = table
        break

    if target_table:
      for tag in target_table.find_all(True):
        if tag.has_attr('rowspan') and not tag['rowspan'].isdigit():
          del tag['rowspan']
        if tag.has_attr('colspan') and not tag['colspan'].isdigit():
          del tag['colspan']
      df = pd.read_html(StringIO(str(target_table)))[0]
      return df
    else:
        print("Table not found")
        return None

dfs = []
for name, link in urls.items():
  dfs.append(url_to_df(link))

